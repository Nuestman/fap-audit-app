"""Generate src/db/seed/protocol-v1.ts and kms-odd-drafts.ts from the audit report folder.

Run once from the app root:  python scripts/generate-seed-data.py
"""

import json
import re
import sys
from pathlib import Path

APP = Path(__file__).resolve().parent.parent
REPORT = APP.parent / "fap-audit-report"
OUT = APP / "src" / "db" / "seed"

sys.path.insert(0, str(REPORT))
import build_workbook  # noqa: E402

SMALL_WORDS = {"and", "or", "of", "the", "for", "to", "in"}


def title_case(text):
    words = text.lower().split()
    out = []
    for i, w in enumerate(words):
        out.append(w if i and w in SMALL_WORDS else w[:1].upper() + w[1:])
    return " ".join(out).replace("Ppe", "PPE")


def parse_protocol():
    sections = []
    subtitles = {}
    question = None
    lines = (REPORT / "protocol.md").read_text(encoding="utf-8").splitlines()
    for raw in lines:
        line = raw.strip()
        if line.startswith("\u201c") and question is None:
            question = line.strip("\u201c\u201d")
        m = re.match(r"^SECTION ([A-I]) [\u2013-] (.+)$", line)
        if m:
            sections.append({"code": m.group(1), "title": title_case(m.group(2)), "items": []})
            continue
        sub = re.match(r"^([A-G]1)\. (.+)$", line)
        if sub:
            subtitles[sub.group(1)[0]] = sub.group(2)
            continue
        crit = re.match(r"^([A-G]\d\.\d+)\t(.+?)\t\u2610Yes", line)
        if crit:
            sections[-1]["items"].append({"code": crit.group(1), "text": crit.group(2).strip()})
    sections = [s for s in sections if s["items"]]
    for s in sections:
        s["subtitle"] = subtitles.get(s["code"])
    return question, sections


def drafts():
    out = {}
    for post in build_workbook.POSTS:
        responses = [
            {
                "code": f["id"],
                "answer": "no" if f.get("response", "No") else None,
                "evidence": f["evidence"],
                "finding": f["finding"],
                "classification": f["cls"],
                "action": f["action"],
                "notes": f["notes"],
            }
            for f in build_workbook.FINDINGS.get(post, [])
        ]
        h1 = [
            {
                "kind": "h1",
                "finding": i["finding"],
                "linkedRef": i["ref"],
                "evidence": i["evidence"],
                "consequence": None,
                "interimControl": None,
                "classification": i["cls"],
                "action": i["recommendation"],
                "notes": i["notes"],
            }
            for i in build_workbook.H1_ITEMS.get(post, [])
        ]
        h3 = [
            {
                "kind": "h3",
                "finding": i["issue"],
                "linkedRef": None,
                "evidence": None,
                "consequence": i["consequence"],
                "interimControl": i["interim"] or None,
                "classification": i["cls"],
                "action": None,
                "notes": i["notes"],
            }
            for i in build_workbook.H3_ITEMS.get(post, [])
        ]
        if responses or h1 or h3:
            out[post] = {"responses": responses, "extras": h1 + h3}
    return out


CLS = {"Major NC": "major_nc", "Minor NC": "minor_nc", "OFI": "ofi", "OBS": "obs", "C": "c"}


def normalise(data):
    for post in data.values():
        for r in post["responses"] + post["extras"]:
            r["classification"] = CLS[r["classification"]]
    return data


def write_ts(path, header, name, type_name, value):
    body = json.dumps(value, indent=2, ensure_ascii=False)
    path.write_text(
        f"{header}\n\nexport const {name}: {type_name} = {body};\n", encoding="utf-8"
    )


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    question, sections = parse_protocol()
    count = sum(len(s["items"]) for s in sections)
    write_ts(
        OUT / "protocol-v1.ts",
        '// Generated by scripts/generate-seed-data.py from protocol.md. Do not edit by hand.\n'
        'import type { ProtocolSeed } from "./types";',
        "PROTOCOL_V1",
        "ProtocolSeed",
        {"centralQuestion": question, "sections": sections},
    )
    write_ts(
        OUT / "kms-odd-drafts.ts",
        "// Generated by scripts/generate-seed-data.py from build_workbook.py. Do not edit by hand.\n"
        'import type { DraftSeed } from "./types";',
        "DRAFTS",
        "DraftSeed",
        normalise(drafts()),
    )
    print(f"{len(sections)} sections, {count} criteria; drafts for {', '.join(drafts())}")


if __name__ == "__main__":
    main()
